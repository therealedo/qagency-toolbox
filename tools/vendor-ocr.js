#!/usr/bin/env node
/* Copies the offline OCR engine into vendor/tesseract/ as plain scripts, so
   the tool reads scans without internet and without fetch (the page blocks
   every connection). Run it again only to update the engine or the languages.

     ocr-loader.js     tesseract.js-core (SIMD + LSTM build) as a string;
                       it runs inside a worker built from a Blob
     ocr-wasm.js       the engine's WebAssembly, gzipped, in base64
     ocr-lang-spa.js   Spanish model (tessdata_best int), gzipped, in base64
     ocr-lang-eng.js   English model, the same

   Usage: node tools/vendor-ocr.js <node_modules folder>
   The folder needs tesseract.js-core@7.0.0, @tesseract.js-data/spa and
   @tesseract.js-data/eng (npm install them in a scratch folder). */
"use strict";

const fs = require("fs");
const path = require("path");
const zlib = require("zlib");

const nm = process.argv[2];
if (!nm || !fs.existsSync(path.join(nm, "tesseract.js-core"))) {
  console.error("Usage: node tools/vendor-ocr.js <node_modules folder with tesseract.js-core>");
  process.exit(1);
}
const root = path.resolve(__dirname, "..");
const out = path.join(root, "vendor", "tesseract");
fs.mkdirSync(out, { recursive: true });
const src = (p) => path.join(nm, p);

/* a "</script" inside the string would close the tag in the single-file build */
const BS = String.fromCharCode(92);
const jsString = (s) => JSON.stringify(s).split("</script").join("<" + BS + "/script")
  .split(String.fromCharCode(0x2028)).join(BS + "u2028")
  .split(String.fromCharCode(0x2029)).join(BS + "u2029");

const core = JSON.parse(fs.readFileSync(src("tesseract.js-core/package.json"), "utf8"));
const loader = fs.readFileSync(src("tesseract.js-core/tesseract-core-simd-lstm.js"), "utf8");
const wasm = zlib.gzipSync(fs.readFileSync(src("tesseract.js-core/tesseract-core-simd-lstm.wasm")), { level: 9 });
const head = (what) => "/* " + what + " — generated by tools/vendor-ocr.js. Apache-2.0, see vendor/tesseract/NOTICE. */\n";

const files = {
  "ocr-loader.js": head("tesseract.js-core " + core.version) + "window.QA_OCR_CORE = " + jsString(loader) + ";\n",
  "ocr-wasm.js": head("tesseract.js-core " + core.version + " WebAssembly, gzip") + 'window.QA_OCR_WASM = "' + wasm.toString("base64") + '";\n'
};
["spa", "eng"].forEach((code) => {
  const data = fs.readFileSync(src("@tesseract.js-data/" + code + "/4.0.0_best_int/" + code + ".traineddata.gz"));
  files["ocr-lang-" + code + ".js"] = head("tessdata_best " + code + " 4.0.0 int, gzip") +
    "window.QA_OCR_LANG = window.QA_OCR_LANG || {};\nwindow.QA_OCR_LANG." + code + ' = "' + data.toString("base64") + '";\n';
});
fs.copyFileSync(src("tesseract.js-core/LICENSE"), path.join(out, "LICENSE"));

Object.keys(files).forEach((name) => {
  fs.writeFileSync(path.join(out, name), files[name]);
  console.log("vendor/tesseract/" + name + "  " + Math.round(Buffer.byteLength(files[name]) / 1024) + " KB");
});
